#!/usr/bin/env bash
###############################################################################
# install.sh - Entrypoint for Coder workspace / Codespaces / new machine
#
# Usage: bash install.sh
###############################################################################

set -e
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "╔══════════════════════════════════════════════════════════════════════════════════╗"
echo "║                        dotfiles installer - ngxxfus                              ║"
echo "║                        Target user: coder (/home/coder)                          ║"
echo "╚══════════════════════════════════════════════════════════════════════════════════╝"
echo ""

# ---------------------------------------------------------------------------
# Step 1: Install APT packages + CLI tools
# ---------------------------------------------------------------------------
echo ">>> [1/4] Installing packages..."
bash "${SCRIPT_DIR}/scripts/install_packages.sh"

# ---------------------------------------------------------------------------
# Step 2: Run full Coder setup (nvim, omz, clangd, jlink, fonts, aliases...)
# ---------------------------------------------------------------------------
echo ">>> [2/4] Running CoderSetupV2..."
bash "${SCRIPT_DIR}/setup/CoderSetupV2.sh"

# ---------------------------------------------------------------------------
# Step 3: Symlink dotfiles via stow
# ---------------------------------------------------------------------------
echo ">>> [3/4] Setting up symlinks..."
bash "${SCRIPT_DIR}/scripts/setup_symlinks.sh"

# ---------------------------------------------------------------------------
# Step 4: Done
# ---------------------------------------------------------------------------
echo ""
echo "╔══════════════════════════════════════════════════════════════════════════════════╗"
echo "║  All done! Run: source ~/.zshrc  or restart your shell.                          ║"
echo "╚══════════════════════════════════════════════════════════════════════════════════╝"